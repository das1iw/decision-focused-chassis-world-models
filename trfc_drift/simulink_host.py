def _pack(typ: int, payload: bytes) -> bytes:
    return struct.pack("<II", typ, len(payload)) + payload


def _f64(*parts) -> bytes:
    return np.concatenate([np.atleast_1d(np.asarray(p, dtype=np.float64)).ravel() for p in parts]).tobytes()


class Link:
    """Framed messages over one connected socket."""

    def __init__(self, sock: socket.socket):
        self.sock = sock
        self.sock.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)

    def send(self, typ: int, payload: bytes = b"") -> None:
        self.sock.sendall(_pack(typ, payload))

    def _recv_exact(self, n: int) -> bytes:
        buf = bytearray()
        while len(buf) < n:
            chunk = self.sock.recv(n - len(buf))
            if not chunk:
                raise ConnectionError("worker closed the connection")
            buf += chunk
        return bytes(buf)

    def recv(self, timeout: float) -> tuple[int, bytes]:
        self.sock.settimeout(timeout)
        try:
            typ, n = struct.unpack("<II", self._recv_exact(8))
            return typ, (self._recv_exact(n) if n else b"")
        finally:
            self.sock.settimeout(None)


# ---------------------------------------------------------------- per-run CarSim files
def write_run_files(run_dir: Path, v0_kph: float, tstop: float, iprint: int = 1000, tag: str = "out") -> Path:
    """Simfile and run parsfile for one Simulink CarSim run. The parsfile reads the verified base parsfile and then
    applies CarSimDLL.start's statements (same order, same number format). Returns the simfile path."""
    cs.ensure_base_par()
    run_dir = Path(run_dir)
    run_dir.mkdir(parents=True, exist_ok=True)
    par = run_dir / f"{tag}_run.par"
    par.write_text("\n".join([
        "PARSFILE", "",
        "! TRFC closed-loop Simulink host run (trfc_drift/simulink_host.py): the base DDEV parsfile, then the",
        "! statements that trfc_drift/carsim_dll.py CarSimDLL.start applies with vs_statement.",
        "OPT_ERROR_DIALOG 0",
        f"PARSFILE {cs.BASE_PAR}",
        "OPT_ERROR_DIALOG 0",
        "OPT_SC 1",
        f"SPEED_TARGET_CONSTANT {v0_kph:.6f}",
        f"TSTOP {tstop:.3f}",
        f"IPRINT {int(iprint)}",
        "", "END", ""]), encoding="ascii")
    fb = run_dir / tag
    sim = run_dir / f"{tag}_simfile.sim"
    sim.write_text("\n".join([
        "SIMFILE", "",
        "! Written by trfc_drift/simulink_host.py for one closed-loop Simulink run.",
        f"FILEBASE {fb}", f"INPUT {par}", f"INPUTARCHIVE {fb}_all.par", f"ECHO {fb}_echo.par",
        f"FINAL {fb}_end.par", f"LOGFILE {fb}_log.txt", f"ERDFILE {fb}.vs",
        f"PROGDIR {cs.PROGDIR}", f"DATADIR {cs.DATADIR}", "PRODUCT_ID CarSim", "PRODUCT_VER 2024.1",
        "VEHICLE_CODE i_i", "EXT_MODEL_STEP 0.00050000", f"PORTS_IMP 1,{N_IMP}", f"PORTS_EXP 1,{N_EXP}",
        "", "END", ""]), encoding="ascii")
    return sim


# ---------------------------------------------------------------- MATLAB worker
class MatlabWorker:
    """A long-lived `matlab -batch` process that runs the closed-loop model once per RUN message. The host listens;
    the worker connects, says HELLO, and then serves RUN until QUIT. Child processes inherit this process's CPU
    affinity (run the host through trfc_wm/run_on_ecores_v1.py)."""

    def __init__(self, log_path: Path, model: str = MODEL, root: Path = ENVELOPE_ROOT, connect_timeout: float = 600.0,
                 extra_env: dict | None = None):
        self.model, self.root = model, Path(root)
        self.log_path = Path(log_path)
        self.log_path.parent.mkdir(parents=True, exist_ok=True)
        self.srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self.srv.bind(("127.0.0.1", 0))
        self.srv.listen(1)
        self.port = self.srv.getsockname()[1]
        env = dict(os.environ)
        MATLAB_TMP.mkdir(parents=True, exist_ok=True)
        env["TMP"] = env["TEMP"] = str(MATLAB_TMP)          # MATLAB .dmr temp files grow; keep them off C:
        env.update(extra_env or {})
        cmd = (f"addpath(fullfile(pwd,'simulink','closedloop')); "
               f"wp25Worker({self.port}, '{self.model}');")
        self._log = open(self.log_path, "ab")
        self.proc = subprocess.Popen([str(MATLAB_EXE), "-batch", cmd], cwd=str(self.root), env=env,
                                     stdout=self._log, stderr=subprocess.STDOUT)
        t0 = time.time()
        self.srv.settimeout(5.0)
        conn = None
        while conn is None:
            try:
                conn, _ = self.srv.accept()
            except socket.timeout:
                if self.proc.poll() is not None:
                    raise RuntimeError(f"MATLAB worker exited ({self.proc.returncode}) before connecting; "
                                       f"see {self.log_path}")
                if time.time() - t0 > connect_timeout:
                    raise RuntimeError("MATLAB worker did not connect")
        self.link = Link(conn)
        typ, payload = self.link.recv(timeout=connect_timeout)
        if typ != HELLO:
            raise RuntimeError(f"expected HELLO, got {typ}")
        self.hello = json.loads(payload.decode("utf-8"))
        self.startup_s = time.time() - t0

    def run(self, job: dict) -> None:
        self.link.send(RUN, json.dumps(job).encode("utf-8"))

    def alive(self) -> bool:
        return self.proc.poll() is None

    def close(self, timeout: float = 120.0) -> None:
        try:
            if self.alive():
                self.link.send(QUIT)
                self.proc.wait(timeout=timeout)
        except Exception:
            pass
        finally:
            if self.alive():
                self.proc.kill()      # the worker is idle here (no CarSim run open), so no seat is held
            try:
                self.link.sock.close()
            except Exception:
                pass
            self.srv.close()
            self._log.close()


# ---------------------------------------------------------------- CarSimClient-compatible proxy
class SimulinkSim:
    """start/step/end/close with CarSimClient semantics, backed by the Simulink closed-loop model."""

    def __init__(self, run_dir: Path, worker: MatlabWorker | None = None, iprint: int = 1000,
                 step_timeout_s: float = 300.0, start_timeout_s: float = 1800.0):
        self.run_dir = Path(run_dir)
        self.run_dir.mkdir(parents=True, exist_ok=True)
        self.iprint = iprint
        self.worker = worker if worker is not None else MatlabWorker(self.run_dir / "worker_log.txt")
        self.link = self.worker.link
        self.step_timeout_s, self.start_timeout_s = step_timeout_s, start_timeout_s
        self._mutex = cs.GlobalMutex("Local\\trfc_drift_carsim_setup_v2", timeout_s=7200.0)
        self._imp = np.zeros(N_IMP)
        self.running = False
        self.pending = None           # "REF" (host owes REF for the last STATE) | "CMD" (owes CMD for the last CAND)
        self.k = -1
        self.t = 0.0
        self.runs = 0
        self.failures = 0
        self.source = SOURCE["host"]  # set by the runner before env.step; recorded by the model
        self.last_done = None         # the worker's DONE record of the last run
        self.last_cand = None
        self.timing = dict(state_wait_s=0.0, cand_wait_s=0.0, steps=0)
        self.log_mat = None           # diagnostic model variant only: the worker saves plant I/O at 0.5 ms here

    # ------------------------------------------------ internals
    def _recv(self, want: int, timeout: float) -> bytes:
        try:
            typ, payload = self.link.recv(timeout)
        except (socket.timeout, ConnectionError, OSError) as exc:
            self.running, self.pending = False, None
            self.failures += 1
            raise SolverFailure(f"simulink host link: {exc}") from exc
        if typ == DONE:
            self.last_done = json.loads(payload.decode("utf-8"))
            self.running, self.pending = False, None
            raise _RunEnded(self.last_done)
        if typ != want:
            self.running, self.pending = False, None
            self.failures += 1
            raise SolverFailure(f"simulink host protocol: expected {want}, got {typ}")
        return payload

    def _state(self, payload: bytes) -> np.ndarray:
        v = np.frombuffer(payload, dtype=np.float64)
        k, t = int(round(v[0])), float(v[1])
        if k != self.k + 1:
            raise SolverFailure(f"simulink host: step {k} after {self.k}")
        self.k, self.t = k, t
        self.pending = "REF"
        return v[2:2 + N_EXP].copy()

    def _answer_ref(self, ref: np.ndarray | None, done: bool = False) -> tuple[np.ndarray, np.ndarray]:
        assert self.pending == "REF", self.pending
        r = np.zeros(N_REF) if ref is None else np.asarray(ref, dtype=np.float64)
        self.link.send(REF, _f64(self.k, 1.0 if done else 0.0, r))
        if done:
            self.pending = None
            return np.zeros(N_CAND), np.zeros(N_DIAG)
        t0 = time.perf_counter()
        v = np.frombuffer(self._recv(CAND, self.step_timeout_s), dtype=np.float64)
        self.timing["cand_wait_s"] += time.perf_counter() - t0
        if int(round(v[0])) != self.k:
            raise SolverFailure(f"simulink host: CAND for step {int(v[0])} at step {self.k}")
        self.pending = "CMD"
        u, d = v[1:1 + N_CAND].copy(), v[1 + N_CAND:1 + N_CAND + N_DIAG].copy()
        self.last_cand = (u, d)
        return u, d

    def _wait_done(self, timeout: float) -> dict:
        while True:
            try:
                typ, payload = self.link.recv(timeout)
            except (socket.timeout, ConnectionError, OSError) as exc:
                self.failures += 1
                raise SolverFailure(f"simulink host link at run end: {exc}") from exc
            if typ == DONE:
                self.last_done = json.loads(payload.decode("utf-8"))
                return self.last_done
            if typ == CAND:            # the model finished its current step; answer with a zero command
                v = np.frombuffer(payload, dtype=np.float64)
                self.link.send(CMD, _f64(v[0], SOURCE["host"], np.zeros(N_IMP)))
            elif typ == STATE:         # should not happen once done was sent; stop again
                v = np.frombuffer(payload, dtype=np.float64)
                self.link.send(REF, _f64(v[0], 1.0, np.zeros(N_REF)))

    # ------------------------------------------------ CarSimClient interface
    def start(self, v0_kph: float, cmd: cs.Command, tstop: float = 3600.0) -> np.ndarray:
        if self.running:
            self.end()
        if not self.worker.alive():
            raise SolverFailure("MATLAB worker is not running")
        simfile = write_run_files(self.run_dir, v0_kph, tstop, self.iprint)
        cmd.to_imports(self._imp)
        self._init_imp = self._imp.copy()
        job = dict(run=self.runs, simfile=str(simfile), tstop=float(tstop), v0_kph=float(v0_kph),
                   imports0=self._init_imp.tolist(), log_mat=str(self.log_mat) if self.log_mat else "")
        self.k, self.pending = -1, None
        with self._mutex:              # serializes CarSim setups machine-wide with the Python harness
            self.worker.run(job)
            try:
                e0 = self._state(self._recv(STATE, self.start_timeout_s))
            except _RunEnded as exc:
                self.failures += 1
                raise SolverFailure(f"simulink run ended at start: {exc.rec.get('message', '')[:2000]}")
        self.runs += 1
        self.running = True
        if not np.all(np.isfinite(e0)):
            self.end()
            raise SolverFailure("nonfinite")
        self._last_e = e0
        return e0

    def candidate(self, ref: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        """Answer the pending REF with real features; return the Simulink controller's (u_S, diagnostics)."""
        if not self.running:
            raise SolverFailure("no simulink run")
        try:
            return self._answer_ref(ref)
        except _RunEnded as exc:
            self.failures += 1
            raise SolverFailure(f"simulink run ended: {exc.rec.get('message', '')[:2000]}")

    def step(self, cmd: cs.Command, n_sub: int) -> tuple[np.ndarray, bool]:
        if n_sub != N_SUB:
            raise ValueError(f"the Simulink bridge runs every {N_SUB} solver steps, not {n_sub}")
        if not self.running:
            raise SolverFailure("no simulink run")
        cmd.to_imports(self._imp)
        try:
            if self.pending == "REF":
                self._answer_ref(None)
            self.link.send(CMD, _f64(self.k, self.source, self._imp))
            self.pending = None
            t0 = time.perf_counter()
            e = self._state(self._recv(STATE, self.step_timeout_s))
            self.timing["state_wait_s"] += time.perf_counter() - t0
            self.timing["steps"] += 1
        except _RunEnded as exc:
            rec = exc.rec
            if rec.get("status", 1) == 0:   # the model reached its stop time: CarSim's stop flag
                return self._last_e.copy(), True
            self.failures += 1
            raise SolverFailure(f"simulink run ended: {rec.get('message', '')[:2000]}")
        if not np.all(np.isfinite(e)):
            self.end()
            raise SolverFailure("nonfinite")
        self._last_e = e
        return e, False

    def end(self) -> str:
        if not self.running:
            return ""
        self.running = False
        try:
            if self.pending == "CMD":
                self.link.send(CMD, _f64(self.k, SOURCE["host"], np.zeros(N_IMP)))
                self.pending = None
                self._state(self._recv(STATE, self.step_timeout_s))
            if self.pending == "REF":
                self._answer_ref(None, done=True)
            rec = self._wait_done(self.step_timeout_s)
        except _RunEnded as exc:
            rec = exc.rec
        except SolverFailure:
            return "simulink host failure at end"
        self.pending = None
        return "" if rec.get("status", 1) == 0 else rec.get("message", "")

    def close(self):
        if self.running:
            self.end()
        self.worker.close()


class _RunEnded(Exception):
    def __init__(self, rec: dict):
        super().__init__(rec.get("message", ""))
        self.rec = rec


# ---------------------------------------------------------------- env glue
def make_env(cfg, sim, seed: int = 0, **kw):
    """DDEVEnv on the Simulink plant. env.py is frozen by earlier protocols, so it is not edited: its CarSimClient
    constructor is swapped for the given proxy during construction only."""
    from trfc_drift import env as E
    orig = E.CarSimClient
    E.CarSimClient = lambda run_dir: sim
    try:
        return E.DDEVEnv(cfg, run_dir=Path(sim.run_dir), seed=seed, isolated=True, **kw)
    finally:
        E.CarSimClient = orig


def _interp_xy(track, s: np.ndarray) -> np.ndarray:
    s = np.asarray(s, dtype=float)
    if track.closed:
        L = track.length
        s = s % L
        xs = np.append(track.s, L)
        xy = np.vstack([track.xy, track.xy[:1]])
    else:
        s = np.clip(s, 0.0, track.length)
        xs, xy = track.s, track.xy
    return np.column_stack([np.interp(s, xs, xy[:, 0]), np.interp(s, xs, xy[:, 1])])


def ref_features(env, active: bool = True, v_cap: float = 0.0) -> np.ndarray:
    """Reference features for the Simulink controller, from the env's current projection on its course (the same
    information the Python planners receive). Preview points are in the vehicle frame (x forward, y left)."""
    c, s = env.cfg, env.state
    pv = env.s_tr + PREVIEW
    if not env.track.closed:
        pv = np.minimum(pv, env.track.length)
    k, _ = env.track.at(pv)
    xy = _interp_xy(env.track, pv)
    dx, dy = xy[:, 0] - s["x"], xy[:, 1] - s["y"]
    cy, sy = np.cos(s["yaw"]), np.sin(s["yaw"])
    xv, yv = cy * dx + sy * dy, -sy * dx + cy * dy
    br = env.beta_ref(pv) if c.task == "drift" else np.zeros(NP)
    mu_hat = env.mu_hat if env.mu_hat is not None else 0.65
    head = [1.0 if c.task == "drift" else 0.0, mu_hat, env.e_lat, env.e_psi, env.track.w, v_cap,
            1.0 if active else 0.0, env.s_prog]
    out = np.concatenate([head, k, xv, yv, br]).astype(np.float64)
    assert out.size == N_REF
    return out
