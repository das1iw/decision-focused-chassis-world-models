"""Python AI host for the closed-loop Simulink/CarSim platform (research/135 M1; Envelope task WP25-T01).

The Simulink model DDEV_ClosedLoop_CarSim (Envelope repository, generated by simulink/build_DDEV_ClosedLoop.m) runs
the CarSim plant (vendor vs_sf block on the CSMU DDEV run, 0.5 ms) and the physics chassis controller. A MATLAB
worker process (simulink/closedloop/wp25Worker.m) runs one sim() per CarSim run and talks to this host over one
localhost TCP connection. Each 20 ms control step makes two exchanges through the model's bridge blocks:

    STATE (Simulink -> host)  k, t, the 64 raw CarSim exports at t_k
    REF   (host -> Simulink)  k, done flag, reference features for the Simulink controller (course preview)
    CAND  (Simulink -> host)  k, the controller's candidate action u_S (normalized 4WS_TV), diagnostics
    CMD   (host -> Simulink)  k, command source, the 24 raw CarSim imports held over [t_k, t_k + 20 ms)

SimulinkSim has the CarSimClient interface (start/step/end/close), so DDEVEnv, the friction probe, the scripted
recovery, the planners and the scoring run unchanged; only the plant host changes. Between env steps a runner may
call candidate(ref) to answer the pending REF with real features and read u_S. Scripted steps (probe, recovery)
answer it with an idle REF automatically.

Each CarSim run gets its own simfile and run parsfile. The parsfile links the verified base parsfile
(carsim_dll.BASE_PAR) and then applies the statements that CarSimDLL.start applies with vs_statement, in the same
order and number format.

Framing: every message is a little-endian header (uint32 type, uint32 payload bytes) followed by the payload,
written with a single send so that Nagle's algorithm cannot hold a message back.
"""

